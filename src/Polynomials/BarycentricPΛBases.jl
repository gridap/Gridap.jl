function _PΛ_F_bubble_functions(r,k,D,F,w)
  N = D + 1
  bubble_functions = BubbleFunction[]
  empty_vec = Int[]
  for α in bernstein_terms(r,D)
    for J in sorted_combinations(N,k)
      j = _minimum_or_one(setdiff(F,J))-1
      if issetequal(_support(α) ∪ J, F) && all(α[1:j] .== 0)
        w += 1
        α_id = bernstein_term_id(α)
        push!(bubble_functions, (w, α, α_id, J, empty_vec, empty_vec))
      end
    end
  end
  bubble_functions
end

"""
    PΛ_bubbles(r,k,D)

Generates the indices caracterizing the basis function of `BarycentricPΛBasis`,
described in the Bernstein bases algorithm Developper notes of the official
documentation, and are used as follows:

    for (F, bubble_functions) in PΛ_bubbles(r,k,D)
      for (w, α, α_id, J) in bubble_functions
        # ...
      end
    end
"""
function PΛ_bubbles(r,k,D)
  bubbles = Bubble[]
  if r == 0
    F = [1:(D+1)...]
    α = zeros(Int,D+1)
    bubble_functions = BubbleFunction[]
    for i in 1:binomial(D,k)
      push!(bubble_functions, (i, α, 1, [], [], [])) # J has no meaning there
    end
    push!(bubbles, (F, bubble_functions))
    return bubbles
  end
  # r > 0
  w=0
  for d in k:D
    for F in sorted_combinations(D+1, d+1; right_to_left=true)
      bubble_functions = _PΛ_F_bubble_functions(r,k,D,F,w)
      isempty(bubble_functions) && continue
      push!(bubbles, (F, bubble_functions))
      w += length(bubble_functions)
    end
  end
  @check w == binomial(r+k,k)*binomial(D+r,D-k)
  bubbles
end

function _compute_PΛ_basis_form_coefficient!(Ψ,r,k,::Val{D},b,vertices,indices,flavor=:AFW) where D
  N = D+1
  Vk = Val(k)
  V = eltype(Ψ)

  iszero(r) && return _order_0_Ψ!(Ψ)

  T = eltype(V)
  α_prec = ntuple(_->-1, N)
  φ_αF = MMatrix{D,N,T}(undef)
  Ψw = Mutable(V)(undef)
  @inbounds for (F, bubble_functions) in indices.bubbles
    for (w, α, _, J) in bubble_functions
      if α ≠ α_prec
        _update_φ_αF!(φ_αF,b,α,F,r,flavor)
        α_prec = α
      end

      for (I_id, I, I_sgn) in indices.components
        Ψw[I_id] = I_sgn * _minor(φ_αF,I,J,Vk)
      end
      Ψ[w] = Ψw
    end
  end
  nothing
end

"""
    _update_φ_αF!(φ_αF, b, α, F, r, flavor)

Set in place the `D`×`N` matrix `φ_αF` the direction 1-forms `φ_αF[:,j] =
φ^{α,F,j}` where

    φ^{α,F,j} = dλʲ - (sⱼ/|s|) Σ_{l∈F} dλˡ,     1 ≤ j ≤ N.

`flavor` selects which multi-index weights the correction term:
- `:AFW` uses `s=α` and `r` = |`α`|,
- `:BMM` uses the support indicator of `α` and its cardinal.
"""
@inline function _update_φ_αF!(φ_αF,b::BernsteinBasisOnSimplex{D},α,F,r,flavor=:AFW) where D
  M = b.x_to_λ
  s = ntuple(j -> α[j], Val(D+1))
  if flavor === :BMM
    s = map(αj -> Int(αj > 0), s) #  s  in paper
    r = sum(s)                    # |s| in paper
  end
  @inbounds for ci in CartesianIndices(φ_αF)
    i, j = ci[1], ci[2]
    mF = sum(M[Fl,i+1] for Fl in F; init=0)
    φ_αF[ci] = M[j,i+1] - s[j]*mF/r
  end
end

function _order_0_Ψ!(Ψ)
  V = eltype(Ψ)
  T = eltype(V)
  for w in eachindex(Ψ)
    Ψ[w] = ntuple( i -> T(i==w), length(V))
  end
  nothing
end


