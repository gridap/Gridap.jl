# Do print some BarycentricPΛIndices generated by PΛ_bubbles(r,k,D) in REPL before
# reading this...

# All types and fields "XX" below should be understood as "Indices_For_XX"

# One bubble function:
#               ω_w  =      (  w,           α, α_id,           J,   sub_J_ids,  sup_α_ids )
const BubbleFunction = Tuple{Int, Vector{Int},  Int, Vector{Int}, Vector{Int}, Vector{Int}}

# One bubble space associated to the d-dimensional face F
# bubble_d_F =      (          F,    F_bubble_functions )
const Bubble = Tuple{Vector{Int}, Vector{BubbleFunction}}

"""
    struct BarycentricPΛIndices
      identity::UInt
      bubbles::Vector{Bubble}
      components::Vector{Tuple{ Int, Vector{Int}, Int}}
    end

For storing indices in `BarycentricP(m)ΛBasis`. The `bubbles` are generated by
[`PΛ_bubbles`](@ref) or [`PmΛ_bubbles`](@ref), the `components` by
[`_basis_forms_components`](@ref).
"""
struct BarycentricPΛIndices
  # An objectid is stored here to keep track of what's inside and perform a
  # sanity check when reusing the indices elsewhere:
  #     identity = objectid( (r,k,D,:P,false,false) )
  # for a PᵣΛᵏ(△ᴰ) basis indices with vector-proxied components and rotate_90=false.
  identity::UInt

  # bubble indices given by P(m)Λ_bubbles (can be filtered and renumbered to select subset of bubbles)
  # The BubbleFunction[1] "w" MUST be in increasing order when iterating over bubbles and bubble_functions
  bubbles::Vector{Bubble}

  # Indices for the components of a basis k-form or its vector calculus proxy,
  #                       (I_id,           I, sgnIcomp), see _basis_forms_components .
  components::Vector{Tuple{ Int, Vector{Int},      Int}}

  # Components "I" of the exterior derivative of a basis polynomial form
  # ext_deriv_components::Vector{Component}
end

function _check_PΛ_indices(r,k,D,F,DG_style, indices::BarycentricPΛIndices, rot_90)
  @check F ∈ (:P,:P⁻)
  # Changing one of those requires re-computing all fields of BarycentricPΛIndices,
  # otherwise wrong result or segfault due to @inbounds in evaluating functions
  # are expected
  @assert objectid( (r,k,D,F,DG_style,rot_90) ) == indices.identity

  @check begin
    ordered_bf_ids = [ bubfun[1] for bub in indices.bubbles for bubfun in bub[2] ]
    C = length(ordered_bf_ids)
    ordered_bf_ids == 1:C
  end "Invalid BarycentricPΛIndices: bubble functions are not numbered from 1 to length(b) in the bubble indices"

  @check begin
    unique_faces = Set()
    for bubble in indices.bubbles
      push!(unique_faces, sort(bubble[1]))
    end
    length(unique_faces) == length(indices.bubbles)
  end """
    Invalid BarycentricPΛIndices: all bubble functions to a face must be
    gathered in a unique Bubble, duplicated bubble faces were found in the given
    indices
  """
end

"""
    _last_bubble_function_index(ids::BarycentricPΛIndices)

The index of the last bubble function in `ids`, that is also the number of basis
polynomial defined by `ids`, and cardinal of the owning basis.
"""
function _last_bubble_function_index(ids::BarycentricPΛIndices)
  isempty(ids.bubbles) && return 0
  return ids.bubbles[end][2][end][1]
end

function Base.show(io::IO, ::MIME"text/plain", indices::BarycentricPΛIndices)
  if isempty(indices.bubbles)
    print(io,"Empty PΛ basis indices")
    return
  end

  α = indices.bubbles[1][2][1][2]
  J = indices.bubbles[1][2][1][4]
  I = indices.components[1][2]

  r = sum(α)+length(J)-length(I)
  k = length(I)
  D = length(α)-1
  is_Pm = r != sum(α)
  basis_str = "Pᵣ"* (is_Pm ? "⁻" : "") * "Λᵏ(△ᴰ) "
  println(io, basis_str, "basis indices, r=$r k=$k D=$D")

  println(io)
  println(io,"Basis polynomial components")
  println(io,"\tI_id\t I\t I_sgn")
  for (I_id, I, I_sgn) in indices.components
    println(io,"\t$I_id\t $(join(I))\t $I_sgn")
  end

  println(io)
  _print_bubble_table(io, indices, :AFW, nothing)
  println(io)
  println(io, basis_str, "basis indices, r=$r k=$k D=$D")
end

"""
    _print_bubble_table(out, indices, flavor, Ψ)

Print the column header and one row per bubble function of `indices`, the
common body of [`print_indices`](@ref) and of the `BarycentricPΛIndices`
`show` method.

`P⁻` index sets wedge `k`+1 barycentric differentials where `P` ones wedge
`k`, which is what tells the two apart here.

`Ψ` holds the direction form of each bubble function and is known only to a
`BarycentricPΛBasis`; pass `nothing` to leave that column empty.
"""
function _print_bubble_table(out::IO, indices::BarycentricPΛIndices, flavor::Symbol, Ψ)
  isempty(indices.bubbles) && return

  k = length(indices.components[1][2])
  is_Pm = length(indices.bubbles[1][2][1][4]) != k

  # :BMM indexes its direction form by a single vertex, which the rotating-basis
  # literature calls k, and its Whitney form by the pair the trimmed one calls e.
  J_title = flavor === :BMM && isone(k) ? (is_Pm ? "e" : "k") : "J"
  # :BMM scales a P⁻ basis function by the bare monomial λ^α instead of Bα.
  bare = is_Pm && flavor === :BMM

  form_title = is_Pm ? "sub_J_ids" : "Ψ"
  form(w, sub_J_ids) = is_Pm ? join(sub_J_ids,",") : (isnothing(Ψ) ? "" : "$(Ψ[w])")
  form_width = max(length(form_title),
                   maximum(length(form(bf[1], bf[5])) for (_, bfs) in indices.bubbles for bf in bfs)) + 2

  println(out,
    rpad("w",4), rpad("F",10), rpad(J_title,8), rpad("α",14),
    rpad(bare ? "λ^α" : "Bα(λ)",18), rpad(form_title,form_width), "α_id")

  for (F, bubble_functions) in indices.bubbles
    for (w, α, α_id, J, sub_J_ids) in bubble_functions
      mono = _monomial_string(α; coeff = bare ? 1 : multinomial(α...))
      println(out,
        rpad("$w",4), rpad(join(F,","),10), rpad(join(J,","),8),
        rpad("$(Tuple(α))",14), rpad(mono,18),
        rpad(form(w, sub_J_ids),form_width), α_id)
    end
  end
end


